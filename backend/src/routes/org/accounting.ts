// ── Settings: legal identity, chart of accounts and mappings ──────────────

router.get("/accounting/settings", requirePerm("accounting.view"), async (req, res) => {
  const ctx = getOrg(req);
  await ensureChart(db, ctx.org.id);
  const [chart, mappings, accounts] = await Promise.all([
    db.select().from(orgLedgerAccountsTable).where(eq(orgLedgerAccountsTable.orgId, ctx.org.id)).orderBy(asc(orgLedgerAccountsTable.code)),
    db.select().from(orgAccountMappingsTable).where(eq(orgAccountMappingsTable.orgId, ctx.org.id)),
    db.select({ id: orgFinanceAccountsTable.id, name: orgFinanceAccountsTable.name, kind: orgFinanceAccountsTable.kind, ledgerCode: orgFinanceAccountsTable.ledgerCode })
      .from(orgFinanceAccountsTable).where(eq(orgFinanceAccountsTable.orgId, ctx.org.id)),
  ]);
  res.json({
    identity: { legalName: ctx.org.legalName, ice: ctx.org.ice, taxId: ctx.org.taxId, registryNumber: ctx.org.registryNumber, address: ctx.org.address },
    chart, mappings, accounts, defaults: DEFAULT_MAPPINGS,
  });
});

const code = z.string().trim().regex(/^\d{4,10}$/, "Account numbers are 4–10 digits");
const SettingsSchema = z.object({
  identity: z.object({
    legalName: optionalText(200),
    ice: z.string().trim().regex(/^\d{15}$/, "ICE must be 15 digits").nullish().or(z.literal("")).transform((v) => v || null),
    taxId: z.string().trim().regex(/^\d{1,15}$/, "IF must be digits only").nullish().or(z.literal("")).transform((v) => v || null),
    registryNumber: optionalText(60),
    address: optionalText(400),
  }),
  accounts: z.array(z.object({ code, label: z.string().trim().min(2).max(160) })).max(200),
  mappings: z.array(z.object({ kind: z.enum(["expense_category", "funding_type"]), key: z.string().trim().min(1).max(80), accountCode: code })).max(200),
  treasury: z.array(z.object({ id: z.coerce.number().int().positive(), ledgerCode: code })).max(100),
});

// Mapping changes only affect entries posted afterwards — existing entries are never rewritten.
router.patch("/accounting/settings", requirePerm("accounting.manage"), validatePatch(SettingsSchema), async (req, res) => {
  const ctx = getOrg(req);
  const body = req.body as Partial<z.infer<typeof SettingsSchema>>;
  if (body.identity) {
    const changes = diff(ctx.org, body.identity);
    await db.update(organisationsTable).set({ ...body.identity, updatedAt: new Date() }).where(eq(organisationsTable.id, ctx.org.id));
    if (Object.keys(changes.after).length) await recordOrgAudit({ orgId: ctx.org.id, actorUserId: ctx.userId, action: "accounting.identity_updated", entityType: "organisation", entityId: ctx.org.id, ...changes });
  }
  for (const a of body.accounts ?? []) {
    await db.insert(orgLedgerAccountsTable).values({ orgId: ctx.org.id, ...a })
      .onConflictDoUpdate({ target: [orgLedgerAccountsTable.orgId, orgLedgerAccountsTable.code], set: { label: a.label } });
  }
  const known = new Set((await db.select({ code: orgLedgerAccountsTable.code }).from(orgLedgerAccountsTable).where(eq(orgLedgerAccountsTable.orgId, ctx.org.id))).map((r) => r.code));
  const unknown = [...(body.mappings ?? []).map((m) => m.accountCode), ...(body.treasury ?? []).map((t) => t.ledgerCode)].filter((c) => !known.has(c));
  if (unknown.length) {
    badRequest(res, `Add these accounts to the chart first: ${[...new Set(unknown)].join(", ")}`);
    return;
  }
  for (const m of body.mappings ?? []) {
    await db.insert(orgAccountMappingsTable).values({ orgId: ctx.org.id, ...m })
      .onConflictDoUpdate({ target: [orgAccountMappingsTable.orgId, orgAccountMappingsTable.kind, orgAccountMappingsTable.key], set: { accountCode: m.accountCode } });
  }
  for (const t of body.treasury ?? []) {
    await db.update(orgFinanceAccountsTable).set({ ledgerCode: t.ledgerCode })
      .where(and(eq(orgFinanceAccountsTable.id, t.id), eq(orgFinanceAccountsTable.orgId, ctx.org.id)));
  }
  if (body.accounts?.length || body.mappings?.length || body.treasury?.length) {
    await recordOrgAudit({ orgId: ctx.org.id, actorUserId: ctx.userId, action: "accounting.mapping_updated", entityType: "organisation", entityId: ctx.org.id, after: { accounts: body.accounts?.length ?? 0, mappings: body.mappings?.length ?? 0, treasury: body.treasury?.length ?? 0 } });
  }
  res.json({ success: true });
});

