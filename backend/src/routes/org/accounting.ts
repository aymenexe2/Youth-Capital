// Accounting Pro: the legal double-entry view of what Finance recorded.
// Read-only (entries are generated by the posting engine); this module only
// reads, exports, configures the mapping and locks periods.

const router: IRouter = Router({ mergeParams: true });

const yearOf = (q: unknown) => {
  const y = Number(q);
  return Number.isInteger(y) && y >= 2000 && y <= 2100 ? y : new Date().getFullYear();
};
const cents = (v: unknown) => Math.round(Number(v ?? 0) * 100);
const amount = (c: number) => (c / 100).toFixed(2);

// ── Overview ───────────────────────────────────────────────────────────────

router.get("/accounting/overview", requirePerm("accounting.view"), async (req, res) => {
  const ctx = getOrg(req);
  const year = yearOf(req.query.year);
  const o = ctx.org.id;
  const [[totals], [unposted], [missingPieces], [missingIce], locks, years] = await Promise.all([
    db.execute(sql`select count(distinct e.id) as entries, coalesce(sum(l.debit),0) as debit, coalesce(sum(l.credit),0) as credit
      from org_journal_entries e join org_journal_lines l on l.entry_id = e.id where e.org_id = ${o} and e.fiscal_year = ${year}`).then((r) => r.rows as any[]),
    db.execute(sql`select count(*) as n from org_transactions t where t.org_id = ${o} and t.status in ('paid','received','posted')
      and not exists (select 1 from org_journal_entries e where e.transaction_id = t.id)`).then((r) => r.rows as any[]),
    db.execute(sql`select count(*) as n from org_journal_entries e where e.org_id = ${o} and e.fiscal_year = ${year} and e.transaction_id is not null
      and e.reverses_entry_id is null and not exists (select 1 from org_files f where f.org_id = e.org_id and f.entity_type = 'transaction' and f.entity_id = e.transaction_id)`).then((r) => r.rows as any[]),
    db.execute(sql`select count(*) as n from org_journal_entries e join org_transactions t on t.id = e.transaction_id
      where e.org_id = ${o} and e.fiscal_year = ${year} and t.kind = 'expense' and t.supplier_ice is null`).then((r) => r.rows as any[]),
    db.select().from(orgAccountingLocksTable).where(and(eq(orgAccountingLocksTable.orgId, o), eq(orgAccountingLocksTable.fiscalYear, year))),
    db.execute(sql`select distinct fiscal_year as y from org_journal_entries where org_id = ${o} order by 1 desc`).then((r) => r.rows.map((x: any) => Number(x.y))),
  ]);
  res.json({
    year, currency: ctx.org.currency,
    entries: Number(totals.entries), debit: amount(cents(totals.debit)), credit: amount(cents(totals.credit)),
    balanced: cents(totals.debit) === cents(totals.credit),
    unposted: Number(unposted.n), missingPieces: Number(missingPieces.n), missingSupplierIce: Number(missingIce.n),
    locks: locks.map((l) => l.month).sort((a, b) => a - b),
    years: [...new Set([year, ...years])].sort((a, b) => b - a),
    identity: { legalName: ctx.org.legalName, ice: ctx.org.ice, taxId: ctx.org.taxId, registryNumber: ctx.org.registryNumber, address: ctx.org.address },
  });
});

// ── Journal ────────────────────────────────────────────────────────────────

async function journal(ctx: OrgContext, filters: { year: number; from?: string | null; to?: string | null; journalCode?: string | null; accountCode?: string | null }) {
  const conds: SQL[] = [eq(orgJournalEntriesTable.orgId, ctx.org.id), eq(orgJournalEntriesTable.fiscalYear, filters.year)];
  if (filters.from) conds.push(gte(orgJournalEntriesTable.date, filters.from));
  if (filters.to) conds.push(lte(orgJournalEntriesTable.date, filters.to));
  if (filters.journalCode) conds.push(eq(orgJournalEntriesTable.journalCode, filters.journalCode));
  const entries = await db.select().from(orgJournalEntriesTable).where(and(...conds)).orderBy(asc(orgJournalEntriesTable.number));
  const ids = entries.map((e) => e.id);
  const [lines, files] = await Promise.all([
    ids.length ? db.select().from(orgJournalLinesTable).where(inArray(orgJournalLinesTable.entryId, ids)).orderBy(asc(orgJournalLinesTable.entryId), asc(orgJournalLinesTable.lineNo)) : [],
    ids.length ? db.select({ entityId: orgFilesTable.entityId, id: orgFilesTable.id, fileName: orgFilesTable.fileName }).from(orgFilesTable)
      .where(and(eq(orgFilesTable.orgId, ctx.org.id), eq(orgFilesTable.entityType, "transaction"),
        inArray(orgFilesTable.entityId, entries.map((e) => e.transactionId).filter((x): x is number => x != null).concat([-1])))) : [],
  ]);
  // A reversal's supporting document is the original's.
  const byId = new Map(entries.map((e) => [e.id, e]));
  return entries.map((e) => {
    const pieceTx = e.reversesEntryId ? byId.get(e.reversesEntryId)?.transactionId ?? e.transactionId : e.transactionId;
    return {
      ...e,
      lines: (lines as any[]).filter((l) => l.entryId === e.id),
      files: (files as any[]).filter((f) => f.entityId === pieceTx).map(({ entityId, ...f }) => f),
    };
  });
}

router.get("/accounting/journal", requirePerm("accounting.view"), async (req, res) => {
  const ctx = getOrg(req);
  const day = (v: unknown) => (typeof v === "string" && /^\d{4}-\d{2}-\d{2}$/.test(v) ? v : null);
  const entries = await journal(ctx, {
    year: yearOf(req.query.year), from: day(req.query.from), to: day(req.query.to),
    journalCode: typeof req.query.journal === "string" && /^[A-Z]{2}$/.test(req.query.journal) ? req.query.journal : null,
  });
  res.json({ entries });
});

// ── General ledger (grand livre) for one account, with running balance ─────

router.get("/accounting/ledger", requirePerm("accounting.view"), async (req, res) => {
  const ctx = getOrg(req);
  const year = yearOf(req.query.year);
  const code = typeof req.query.account === "string" && /^\d{2,10}$/.test(req.query.account) ? req.query.account : null;
  if (!code) {
    badRequest(res, "Choose an account");
    return;
  }
  const base = and(eq(orgJournalLinesTable.orgId, ctx.org.id), eq(orgJournalLinesTable.accountCode, code));
  const [[opening], rows, [acc]] = await Promise.all([
    db.select({ d: sql<string>`coalesce(sum(${orgJournalLinesTable.debit}),0)`, c: sql<string>`coalesce(sum(${orgJournalLinesTable.credit}),0)` })
      .from(orgJournalLinesTable).innerJoin(orgJournalEntriesTable, eq(orgJournalEntriesTable.id, orgJournalLinesTable.entryId))
      .where(and(base, lt(orgJournalEntriesTable.fiscalYear, year))),
    db.select({ line: orgJournalLinesTable, number: orgJournalEntriesTable.number, date: orgJournalEntriesTable.date, journalCode: orgJournalEntriesTable.journalCode, pieceRef: orgJournalEntriesTable.pieceRef })
      .from(orgJournalLinesTable).innerJoin(orgJournalEntriesTable, eq(orgJournalEntriesTable.id, orgJournalLinesTable.entryId))
      .where(and(base, eq(orgJournalEntriesTable.fiscalYear, year))).orderBy(asc(orgJournalEntriesTable.date), asc(orgJournalEntriesTable.number), asc(orgJournalLinesTable.lineNo)),
    db.select().from(orgLedgerAccountsTable).where(and(eq(orgLedgerAccountsTable.orgId, ctx.org.id), eq(orgLedgerAccountsTable.code, code))),
  ]);
  let running = cents(opening.d) - cents(opening.c);
  const openingBalance = running;
  res.json({
    account: { code, label: acc?.label ?? rows[0]?.line.accountLabel ?? code },
    opening: amount(openingBalance),
    lines: rows.map((r) => {
      running += cents(r.line.debit) - cents(r.line.credit);
      return { ...r.line, number: r.number, date: r.date, journalCode: r.journalCode, pieceRef: r.pieceRef, balance: amount(running) };
    }),
    closing: amount(running),
  });
});

// ── Trial balance (balance) ────────────────────────────────────────────────

async function trialBalance(orgId: number, year: number) {
  const rows = (await db.execute(sql`
    select l.account_code as code, max(l.account_label) as label,
      coalesce(sum(case when e.fiscal_year < ${year} then l.debit - l.credit end), 0) as opening,
      coalesce(sum(case when e.fiscal_year = ${year} then l.debit end), 0) as debit,
      coalesce(sum(case when e.fiscal_year = ${year} then l.credit end), 0) as credit
    from org_journal_lines l join org_journal_entries e on e.id = l.entry_id
    where l.org_id = ${orgId} and e.fiscal_year <= ${year}
    group by l.account_code order by l.account_code`)).rows as any[];
  // Income and expense accounts (classes 6, 7) restart each year; balance-sheet accounts carry forward.
  const accounts = rows.map((r) => {
    const carry = /^[67]/.test(r.code) ? 0 : cents(r.opening);
    const closing = carry + cents(r.debit) - cents(r.credit);
    return { code: r.code, label: r.label, opening: amount(carry), debit: amount(cents(r.debit)), credit: amount(cents(r.credit)), closing: amount(closing),
      closingDebit: amount(Math.max(closing, 0)), closingCredit: amount(Math.max(-closing, 0)) };
  }).filter((a) => cents(a.opening) || cents(a.debit) || cents(a.credit));
  const sum = (k: "debit" | "credit" | "closingDebit" | "closingCredit") => accounts.reduce((s, a) => s + cents(a[k]), 0);
  const totals = { debit: amount(sum("debit")), credit: amount(sum("credit")), closingDebit: amount(sum("closingDebit")), closingCredit: amount(sum("closingCredit")) };
  return { accounts, totals, balanced: sum("debit") === sum("credit") && sum("closingDebit") === sum("closingCredit") };
}

router.get("/accounting/balance", requirePerm("accounting.view"), async (req, res) => {
  const ctx = getOrg(req);
  const year = yearOf(req.query.year);
  res.json({ year, ...(await trialBalance(ctx.org.id, year)) });
});

// ── Financial statements: CPC and Bilan (simplified model) ────────────────

router.get("/accounting/statements", requirePerm("accounting.view"), async (req, res) => {
  const ctx = getOrg(req);
  const year = yearOf(req.query.year);
  const { accounts, balanced } = await trialBalance(ctx.org.id, year);
  const pick = (re: RegExp, sign: 1 | -1) => accounts.filter((a) => re.test(a.code)).map((a) => ({ code: a.code, label: a.label, amount: amount(sign * cents(a.closing)) }));
  const total = (rows: { amount: string }[]) => rows.reduce((s, r) => s + cents(r.amount), 0);
  // CPC: products are credit balances of class 7, charges debit balances of class 6.
  const produits = pick(/^7/, -1);
  const charges = pick(/^6/, 1);
  const result = total(produits) - total(charges);
  // Bilan: assets = debit balances of classes 2–5; liabilities = credit balances of 1, 4, 5 plus the year's result.
  const actif = accounts.filter((a) => /^[2-5]/.test(a.code) && cents(a.closing) > 0).map((a) => ({ code: a.code, label: a.label, amount: amount(cents(a.closing)) }));
  const passif = accounts.filter((a) => /^[1-5]/.test(a.code) && cents(a.closing) < 0).map((a) => ({ code: a.code, label: a.label, amount: amount(-cents(a.closing)) }));
  res.json({
    year, currency: ctx.org.currency, balanced,
    cpc: { produits, charges, totalProduits: amount(total(produits)), totalCharges: amount(total(charges)), resultat: amount(result) },
    bilan: {
      actif, passif, resultat: amount(result),
      totalActif: amount(total(actif)), totalPassif: amount(total(passif) + result),
    },
    identity: { name: ctx.org.name, legalName: ctx.org.legalName, ice: ctx.org.ice, taxId: ctx.org.taxId, registryNumber: ctx.org.registryNumber, address: ctx.org.address },
  });
});

// ── FEC (Fichier des Écritures Comptables) ─────────────────────────────────

export const FEC_COLUMNS = ["JournalCode", "EcritureNum", "EcritureDate", "CompteNum", "CompteLib", "PieceRef", "PieceDate", "EcritureLib", "Debit", "Credit", "Projet_Analytique"] as const;

async function fecRows(ctx: OrgContext, year: number) {
  const entries = await journal(ctx, { year });
  return entries.flatMap((e) => e.lines.map((l: any) => ({
    JournalCode: e.journalCode, EcritureNum: e.number, EcritureDate: e.date, CompteNum: l.accountCode, CompteLib: l.accountLabel,
    PieceRef: e.pieceRef ?? "", PieceDate: e.pieceDate ?? e.date, EcritureLib: l.label, Debit: l.debit, Credit: l.credit, Projet_Analytique: l.analytic ?? "",
  })));
}

router.get("/accounting/fec", requirePerm("accounting.view"), async (req, res) => {
  const ctx = getOrg(req);
  const year = yearOf(req.query.year);
  const rows = await fecRows(ctx, year);
  await recordOrgAudit({ orgId: ctx.org.id, actorUserId: ctx.userId, action: "accounting.exported", entityType: "organisation", entityId: ctx.org.id, summary: `FEC ${year}`, after: { rows: rows.length } });
  res.json({ year, columns: FEC_COLUMNS, rows });
});

// Plain FEC text file: pipe-separated, dates YYYYMMDD, comma decimals.
router.get("/accounting/fec.txt", requirePerm("accounting.view"), async (req, res) => {
  const ctx = getOrg(req);
  const year = yearOf(req.query.year);
  const rows = await fecRows(ctx, year);
  const clean = (v: unknown) => String(v ?? "").replace(/[|\r\n]+/g, " ").trim();
  const ymd = (d: string) => d.replaceAll("-", "");
  const lines = rows.map((r) => [
    r.JournalCode, r.EcritureNum, ymd(r.EcritureDate), r.CompteNum, clean(r.CompteLib), clean(r.PieceRef), ymd(r.PieceDate), clean(r.EcritureLib),
    r.Debit.replace(".", ","), r.Credit.replace(".", ","), clean(r.Projet_Analytique),
  ].join("|"));
  await recordOrgAudit({ orgId: ctx.org.id, actorUserId: ctx.userId, action: "accounting.exported", entityType: "organisation", entityId: ctx.org.id, summary: `FEC.txt ${year}`, after: { rows: rows.length } });
  res.setHeader("Content-Type", "text/plain; charset=utf-8");
  res.setHeader("Content-Disposition", `attachment; filename="FEC_${(ctx.org.ice || ctx.org.slug).replace(/[^\w-]/g, "")}_${year}1231.txt"`);
  res.send("﻿" + [FEC_COLUMNS.join("|"), ...lines].join("\r\n"));
});

