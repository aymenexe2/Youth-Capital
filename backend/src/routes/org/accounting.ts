// ── Period locking (clôture) ───────────────────────────────────────────────

const LockSchema = z.object({ year: z.coerce.number().int().min(2000).max(2100), month: z.coerce.number().int().min(0).max(12) });

// Locks are final: once a month (or the whole year, month 0) is closed, no
// entry can be dated in it. Before locking, everything must be posted and
// every entry must have its supporting document.
router.post("/accounting/locks", requirePerm("accounting.manage"), validateBody(LockSchema), async (req, res) => {
  const ctx = getOrg(req);
  const { year, month } = req.body as z.infer<typeof LockSchema>;
  const from = month ? `${year}-${String(month).padStart(2, "0")}-01` : `${year}-01-01`;
  const to = month ? new Date(Date.UTC(year, month, 0)).toISOString().slice(0, 10) : `${year}-12-31`;
  const [unposted] = (await db.execute(sql`select count(*) as n from org_transactions t where t.org_id = ${ctx.org.id}
    and t.status in ('paid','received','posted') and t.date between ${from} and ${to}
    and not exists (select 1 from org_journal_entries e where e.transaction_id = t.id)`)).rows as any[];
  if (Number(unposted.n) > 0) {
    conflict(res, `${unposted.n} posted Finance transaction(s) in this period have no journal entry yet — run "Post missing entries" first`);
    return;
  }
  const [missing] = (await db.execute(sql`select count(*) as n from org_journal_entries e where e.org_id = ${ctx.org.id}
    and e.date between ${from} and ${to} and e.transaction_id is not null and e.reverses_entry_id is null
    and not exists (select 1 from org_files f where f.org_id = e.org_id and f.entity_type = 'transaction' and f.entity_id = e.transaction_id)`)).rows as any[];
  if (Number(missing.n) > 0) {
    conflict(res, `${missing.n} entr${Number(missing.n) === 1 ? "y has" : "ies have"} no supporting document — attach them in Finance before closing`);
    return;
  }
  const { balanced } = await trialBalance(ctx.org.id, year);
  if (!balanced) {
    conflict(res, "The trial balance isn't balanced — contact support before closing");
    return;
  }
  const [lock] = await db.insert(orgAccountingLocksTable).values({ orgId: ctx.org.id, fiscalYear: year, month, lockedByUserId: ctx.userId }).onConflictDoNothing().returning();
  if (!lock) {
    conflict(res, "This period is already locked");
    return;
  }
  await recordOrgAudit({ orgId: ctx.org.id, actorUserId: ctx.userId, action: "accounting.period_locked", entityType: "organisation", entityId: ctx.org.id, summary: month ? `${year}-${String(month).padStart(2, "0")}` : `${year}`, after: { year, month } });
  res.status(201).json({ lock });
});

